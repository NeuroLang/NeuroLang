@dataclass(frozen=True)
class ShowRAOptions:
    """
    Options of the relational algebra plan display (``show_ra``).

    Parameters
    ----------
    collapse : bool
        If True (the default), trivial wrappers are collapsed for
        readability, e.g. ``ρ[x, y](π[0, 1](edge))`` is printed as
        ``edge(x, y)``. If False, the plans are printed in full.
    analyze : bool
        If True, the query is run and every node of each plan is
        annotated with the number of rows it produced, as SQL's
        ``EXPLAIN ANALYZE`` does.

    """

    collapse: bool = True
    analyze: bool = False


def show_ra_options(show_ra):
    """
    Return the :class:`ShowRAOptions` requested by ``show_ra``.

    ``show_ra`` is a boolean or a :class:`ShowRAOptions`: ``True`` stands
    for the default options and a false value for no plan display, in
    which case None is returned.
    """
    if isinstance(show_ra, ShowRAOptions):
        return show_ra
    if show_ra:
        return ShowRAOptions()
    return None


QUERY_DISPLAY_NAMES = ("ans", "query", "ans_query")

_GENERATED_NAME = re.compile(
    r"^(fresh_\d+|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$"
)


def is_generated_symbol(symbol):
    """
    Return whether ``symbol`` has a name generated by NeuroLang.

    Generated names are those of fresh symbols (``fresh_00000012``) and
    the UUIDs the frontends name query predicates with.
    """
    return (
        isinstance(symbol, Symbol)
        and not isinstance(symbol, AdornedSymbol)
        and _GENERATED_NAME.match(symbol.name) is not None
    )


def generated_query_symbol(rule):
    """
    Return the generated predicate symbol of a query rule, if any.

    The symbol is the functor of the consequent of ``rule``, without its
    magic-sets adornments; None is returned when its name is not
    generated by NeuroLang, i.e. when the user named the predicate.
    """
    functor = rule.consequent.functor
    while isinstance(functor, AdornedSymbol):
        functor = functor.expression
    if is_generated_symbol(functor):
        return functor
    return None


def query_display_name(symbol_table):
    """
    Return the name a query predicate is displayed with.

    It is ``ans`` unless the program already has an ``ans`` predicate,
    then ``query``.
    """
    for name in QUERY_DISPLAY_NAMES:
        if symbol_table is None or Symbol(name) not in symbol_table:
            return name
    return QUERY_DISPLAY_NAMES[-1]


class RenameSymbolsForDisplay(ExpressionWalker):
    """
    Rename predicate symbols, including adorned ones, for display.

    Parameters
    ----------
    renames : dict
        mapping from symbols to the symbols to display instead.

    """

    def __init__(self, renames):
        """Store the renames to apply."""
        self.renames = renames

    @add_match(AdornedSymbol)
    def adorned_symbol(self, symbol):
        """Rename the symbol an adorned symbol adorns."""
        base = symbol.expression
        if base not in self.renames:
            return symbol
        return AdornedSymbol(
            self.renames[base], symbol.adornment, symbol.number
        )

    @add_match(Symbol)
    def symbol(self, symbol):
        """Rename a symbol."""
        return self.renames.get(symbol, symbol)


class PlanDisplay:
    """
    Print the rules of a program and their relational algebra plans.

    Parameters
    ----------
    options : ShowRAOptions, optional
        how the plans are displayed, the default options when None.
    query_symbol : Symbol, optional
        predicate symbol generated for the query, displayed as ``ans``
        (or ``query`` if ``symbol_table`` has an ``ans`` predicate).
    symbol_table : Mapping, optional
        symbol table of the program.

    Attributes
    ----------
    unknown_size_symbols : set
        predicate symbols whose relation is a placeholder, not printed
        with a size.

    """

    def __init__(self, options=None, query_symbol=None, symbol_table=None):
        """Initialise the display; see the class docstring."""
        self.options = options or ShowRAOptions()
        self.renames = {}
        if query_symbol is not None:
            self.renames[query_symbol] = Symbol(
                query_display_name(symbol_table)
            )
        self.unknown_size_symbols = set()

    def display_expression(self, expression):
        """Return ``expression`` with its symbols renamed for display."""
        if not self.renames:
            return expression
        return RenameSymbolsForDisplay(self.renames).walk(expression)

    def symbol_name(self, symbol):
        """Return the name ``symbol`` is displayed with."""
        symbol = self.display_expression(symbol)
        if isinstance(symbol, AdornedSymbol):
            return str(symbol)
        return symbol.name

    def rule_text(self, rule, fresh_map=None):
        """
        Return the Datalog text of ``rule``.

        The display names of its fresh variables are added to
        ``fresh_map``.
        """
        return DatalogPrettyPrinter(fresh_map).walk(
            self.display_expression(rule)
        )

    def name_map(self, conjunction, symbol_table):
        """
        Return the names the leaves of the plan of ``conjunction`` take.

        The leaves are named after the predicates of ``conjunction`` and
        the relations of ``symbol_table``.
        """
        name_map = build_name_map_from_conjunction(conjunction, symbol_table)
        for symbol in list(name_map):
            if isinstance(symbol, Symbol):
                name_map[symbol] = self.symbol_name(symbol)
        return name_map

    def print_rule(
        self, rule, conjunction, symbol_table, ra_code, leaf_sizes=None,
        column_roles=None,
    ):
        """
        Print the ``--show-ra`` block of a rule.

        The block is the rule header (skipped when ``rule`` is None)
        followed by the pretty-printed RA plan ``ra_code``, whose tables
        are named after the predicates of ``conjunction`` and the
        relations of ``symbol_table``. ``leaf_sizes`` maps the predicate
        symbols of the plan whose size is known to their size. Columns
        named after a variable of the rule are displayed as the variable
        is in the rule header, and those in ``column_roles`` with the
        label it maps them to.
        """
        fresh_map = {}
        if rule is not None:
            print(f"── rule {self.rule_text(rule, fresh_map)} ──")
        name_map = self.name_map(conjunction, symbol_table)
        print(pretty_repr(
            ra_code, name_map=name_map, leaf_sizes=leaf_sizes,
            fresh_map=fresh_map, column_roles=column_roles,
        ))


@lru_cache(maxsize=None)
def show_ra_chase_class(chase_class):
    """Return ``chase_class`` extended with :class:`ShowRAChaseMixin`."""
    return type(
        f"ShowRA{chase_class.__name__}",
        (ShowRAChaseMixin, chase_class),
        {},
    )


def print_deterministic_ra_plan(
    chase_class, program, rules, options=None, query_symbol=None
):
    """
    Print the RA plans of the deterministic stratum ``rules``.

    The stratum is run with ``chase_class`` extended with
    :class:`ShowRAChaseMixin`, displaying the plans with the
    :class:`ShowRAOptions` ``options`` (the default ones when None), and
    the resulting chase solution is returned. ``query_symbol`` is the
    predicate generated for the query, displayed as ``ans``.
    """
    print("── deterministic stratum ──")
    display = PlanDisplay(options, query_symbol, program.symbol_table)
    chase = show_ra_chase(chase_class, program, rules, display)
    return chase.build_chase_solution()


def show_ra_chase(chase_class, program, rules, display=None):
    """
    Build a show-ra chase of ``rules`` over ``program``.

    The chase is an instance of ``chase_class`` extended with
    :class:`ShowRAChaseMixin`, which prints the plans with the
    :class:`PlanDisplay` ``display`` (a default one when None).
    """
    chase = show_ra_chase_class(chase_class)(program, rules=rules)
    chase.show_ra_display = display or PlanDisplay()
    return chase


class ShowRAChaseMixin:
    """
    Chase mixin printing the named RA expression of each rule.

    Before each rule is evaluated, the named RA expression it is
    evaluated with is printed. Errors raised while evaluating a rule
    (e.g. a predicate used with the wrong arity) reach the caller, as
    they do without show-ra. The plans are printed with the
    :class:`PlanDisplay` ``show_ra_display``.
    """

    show_ra_display = PlanDisplay()

    def __init__(self, *args, **kwargs):
        """Initialise the chase with no current rule."""
        super().__init__(*args, **kwargs)
        self._show_ra_current_rule = None

    def chase_step(self, instance, rule, restriction_instance=None):
        """Record ``rule`` as the current rule, then run the step."""
        self._show_ra_current_rule = rule
        return super().chase_step(instance, rule, restriction_instance)

    def obtain_substitutions(
        self, rule_predicates_iterator, instance, restriction_instance
    ):
        """Print the RA plan of the current rule, then evaluate it."""
        predicates = tuple(rule_predicates_iterator)
        if not predicates:
            return []
        conjunction = Conjunction(predicates)
        ra_code = self.translate_conjunction_to_named_ra(conjunction)
        symbol_table = self.ra_symbol_table(
            predicates, instance, restriction_instance
        )
        self.show_ra_display.print_rule(
            getattr(self, "_show_ra_current_rule", None),
            conjunction,
            getattr(self, "datalog_program", None),
            ra_code,
            self._show_ra_leaf_sizes(predicates, symbol_table),
        )
        return super().obtain_substitutions(
            iter(predicates), instance, restriction_instance
        )

    def _show_ra_leaf_sizes(self, predicates, symbol_table):
        """
        Return the sizes of the relations of ``predicates`` known for sure.

        The relations are those of ``symbol_table``, the one the plan is
        evaluated on. Placeholder relations, and in iterative (recursive)
        strata the relations derived by the stratum, which grow at each
        iteration, are left out.
        """
        varying = set()
        if isinstance(self, (ChaseNaive, ChaseSemiNaive)):
            varying = {rule.consequent.functor for rule in self.rules}
        varying |= self.show_ra_display.unknown_size_symbols
        sizes = {}
        for predicate in extract_logic_atoms(Conjunction(predicates)):
            functor = predicate.functor
            if (
                isinstance(functor, Symbol)
                and functor in symbol_table
                and functor not in varying
            ):
                sizes[functor] = len(symbol_table[functor].value)
        return sizes

    def pick_chase_instance_for_stratum(self, stratum, instance_update):
        """Wrap the inner per-stratum chase so its rules print RA too."""
        chase_instance = super().pick_chase_instance_for_stratum(
            stratum, instance_update
        )
        if chase_instance is None:
            return None
        wrapped = show_ra_chase(
            chase_instance.__class__,
            chase_instance.datalog_program,
            Union(tuple(chase_instance.rules)),
            self.show_ra_display,
        )
        wrapped.check_constraints(instance_update)
        return wrapped


def probabilistic_table_names(cpl):
    """
    Map the probabilistic tables of a CP-Logic program to their predicate.

    The keys are the ``id`` of the constants holding the tables of the
    probabilistic facts and choices of ``cpl``, whose first column is
    the probability of each tuple.
    """
    return {
        id(table): symbol.name
        for tables in (cpl.probabilistic_facts(), cpl.probabilistic_choices())
        for symbol, table in tables.items()
    }


def probability_column_roles(plan, provenance_column, tables, rule):
    """
    Return the labels of the probability columns of a probabilistic plan.

    The provenance column of the result, ``provenance_column``, is
    labelled ``p``. The probability column of each table of ``tables``
    (see :func:`probabilistic_table_names`) named by ``plan`` is labelled
    ``p(<predicate>)``, numbered when a table is named more than once.
    Should the rule or the plan use ``p`` as a name, ``prob`` is used.
    """
    rule_variables = extract_logic_free_variables(
        rule.antecedent
    ) | extract_logic_free_variables(rule.consequent)
    names = plan_column_names(plan) | {
        symbol.name for symbol in rule_variables
    }
    label = next(
        candidate for candidate in ("p", "prob", "p_", "prob_")
        if candidate not in names
    )
    roles = {provenance_column: label}
    per_table = {}
    for node in plan_nodes(plan):
        if (
            isinstance(node, NameColumns)
            and isinstance(node.relation, Constant)
            and id(node.relation) in tables
        ):
            column = node.column_names[0].value
            per_table.setdefault(tables[id(node.relation)], []).append(column)
    for table, columns in per_table.items():
        columns = list(dict.fromkeys(columns))
        for number, column in enumerate(columns, start=1):
            suffix = subscript(number) if len(columns) > 1 else ""
            roles.setdefault(column, f"p({table}){suffix}")
    return roles


def plan_nodes(plan):
    """Yield the relational algebra operations and leaves of ``plan``."""
    yield plan
    if not isinstance(plan, RelationalAlgebraOperation):
        return
    for child in plan_children(plan):
        yield from plan_nodes(child)


def plan_children(node):
    """Return the operands of a relational algebra operation."""
    children = []
    for attribute in ("relation", "relation_left", "relation_right"):
        child = getattr(node, attribute, None)
        if isinstance(child, Expression):
            children.append(child)
    children.extend(getattr(node, "relations", ()))
    return tuple(children)


def plan_column_names(plan):
    """Return the names of the columns named by a plan's operators."""
    names = set()
    for node in plan_nodes(plan):
        if isinstance(node, RelationalAlgebraOperation):
            for argument in _flatten(node.unapply()):
                if isinstance(argument, Constant) and isinstance(
                    argument.value, ColumnStr
                ):
                    names.add(str(argument.value))
    return names


def _flatten(arguments):
    """Yield the arguments, and the items of tuple arguments, recursively."""
    for argument in arguments:
        if isinstance(argument, tuple):
            yield from _flatten(argument)
        elif isinstance(argument, FunctionApplicationListMember):
            yield from _flatten(argument.unapply())
        elif isinstance(argument, FunctionApplication):
            yield from _flatten(argument.args)
        else:
            yield argument


class ShowRAStratumSolver(StratumSolver):
    """
    Print the RA plans of each stratum instead of evaluating it.

    The deterministic stratum is run with a show-ra chase, so that the
    probabilistic plans can be built over its solution. The probabilistic
    and post-probabilistic strata are only printed, and an empty
    ``MapInstance`` is returned for them.

    Parameters
    ----------
    engine : NeurolangPDL
        engine whose program is displayed.
    options : ShowRAOptions, optional
        how the plans are displayed, the default options when None.
    query_symbol : Symbol, optional
        predicate symbol generated for the query, displayed as ``ans``.

    """

    def __init__(self, engine, options=None, query_symbol=None):
        """Store the engine and how its plans are displayed."""
        super().__init__(engine)
        self.display = PlanDisplay(
            options, query_symbol, engine.program_ir.symbol_table
        )

    def deterministic(self, det_idb):
        """Print the RA plan of every deterministic rule."""
        print("── deterministic stratum ──")
        chase = show_ra_chase(
            self.engine.chase_class, self.engine.program_ir, det_idb,
            self.display,
        )
        return chase.build_chase_solution()

    def probabilistic(self, solution, prob_idb):
        """Print the optimised RA plan of every probabilistic rule."""
        print("── probabilistic stratum ──")
        engine = self.engine
        cpl, prob_idb = _build_probabilistic_program(
            solution,
            engine.program_ir.probabilistic_facts(),
            engine.program_ir.probabilistic_choices(),
            prob_idb,
            engine.check_qbased_pfact_tuple_unicity,
        )
        dedup = RemoveDuplicatedConjunctsDisjuncts()
        prob_idb = Union(tuple(dedup.walk(r) for r in prob_idb.formulas))
        probability_tables = probabilistic_table_names(cpl)
        for rule in prob_idb.formulas:
            provenance_set = self.rule_provenance_set(rule, cpl)
            plan = self.optimise_plan(provenance_set.relation)
            self.display.print_rule(
                rule,
                rule.antecedent,
                cpl.symbol_table,
                plan,
                column_roles=probability_column_roles(
                    plan, provenance_set.provenance_column.value,
                    probability_tables, rule,
                ),
            )
        return MapInstance()

    def postprobabilistic(self, solution, postprob_idb):
        """Print the RA plan of every post-probabilistic rule."""
        print("── post-probabilistic stratum ──")
        solver = self.engine._build_postprobabilistic_solver(
            solution, postprob_idb
        )
        chase = show_ra_chase(
            self.engine.chase_class, solver, postprob_idb, self.display
        )
        chase.build_chase_solution()
        return MapInstance()

    def rule_provenance_set(self, rule, cpl):
        """
        Build the provenance set of a probabilistic rule without solving it.

        The relational algebra solver is not run, so the returned set holds
        the unevaluated RA plan.
        """
        query = rule
        solve = self._solve_unevaluated_succ_query
        if is_within_language_prob_query(rule):
            query = within_language_succ_query_to_intensional_rule(rule)
            if isinstance(rule.antecedent, Condition):
                # As in the solver (_solve_within_language_prob_query), a
                # conditional query goes through the MARG solver, which
                # splits it into joint and conditioning SUCC queries and
                # does not run the RA solver on them.
                solve = self._solve_unevaluated_marg_query
        solvers = self.engine.probabilistic_solvers
        for succ_solver in solvers:
            try:
                return solve(query, cpl, succ_solver)
            except UnsupportedSolverError:
                if succ_solver == solvers[-1]:
                    raise

    @staticmethod
    def _solve_unevaluated_succ_query(query, cpl, succ_solver):
        """Build the provenance set of a SUCC query without evaluating it."""
        return succ_solver(query, cpl, run_relational_algebra_solver=False)

    @staticmethod
    def _solve_unevaluated_marg_query(rule, cpl, succ_solver):
        """Build the provenance set of a MARG query without evaluating it."""
        return lift_solve_marg_query(rule, cpl, succ_solver)

    @staticmethod
    def optimise_plan(ra_code):
        """
        Optimise an RA plan for display.

        Apply the RA optimiser together with greedy join ordering, then run
        a second optimisation pass after the reordering.
        """
        class ShowRAOptimiser(
            RelationalAlgebraOptimiser,
            DegenerateNaturalJoinToProduct,
            GreedyJoinOrdering,
        ):
            pass
        ra_code = ShowRAOptimiser().walk(ra_code)
        # Second RA optimisation pass after GOO reordering
        return RelationalAlgebraOptimiser().walk(ra_code)
