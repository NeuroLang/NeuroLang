@dataclass(frozen=True)
class ShowRAOptions:
    """
    Options of the relational algebra plan display (``show_ra``).

    Parameters
    ----------
    collapse : bool
        If True (the default), trivial wrappers are collapsed for
        readability, e.g. ``ρ[x, y](π[0, 1](edge))`` is printed as
        ``edge(x, y)``. If False, the plans are printed in full.
    analyze : bool
        If True, the query is run and every node of each plan is
        annotated with the number of rows it produced, as SQL's
        ``EXPLAIN ANALYZE`` does.

    """

    collapse: bool = True
    analyze: bool = False


def show_ra_options(show_ra):
    """
    Return the :class:`ShowRAOptions` requested by ``show_ra``.

    ``show_ra`` is a boolean or a :class:`ShowRAOptions`: ``True`` stands
    for the default options and a false value for no plan display, in
    which case None is returned.
    """
    if isinstance(show_ra, ShowRAOptions):
        return show_ra
    if show_ra:
        return ShowRAOptions()
    return None


QUERY_DISPLAY_NAMES = ("ans", "query", "ans_query")

_FRESH_NAME = re.compile(r"^fresh_\d+$")

_GENERATED_NAME = re.compile(
    r"^(fresh_\d+|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})$"
)


def is_generated_symbol(symbol):
    """
    Return whether ``symbol`` has a name generated by NeuroLang.

    Generated names are those of fresh symbols (``fresh_00000012``) and
    the UUIDs the frontends name query predicates with.
    """
    return (
        isinstance(symbol, Symbol)
        and not isinstance(symbol, AdornedSymbol)
        and _GENERATED_NAME.match(symbol.name) is not None
    )


def generated_query_symbol(rule):
    """
    Return the generated predicate symbol of a query rule, if any.

    The symbol is the functor of the consequent of ``rule``, without its
    magic-sets adornments; None is returned when its name is not
    generated by NeuroLang, i.e. when the user named the predicate.
    """
    functor = rule.consequent.functor
    while isinstance(functor, AdornedSymbol):
        functor = functor.expression
    if is_generated_symbol(functor):
        return functor
    return None


def query_display_name(symbol_table):
    """
    Return the name a query predicate is displayed with.

    It is ``ans`` unless the program already has an ``ans`` predicate,
    then ``query``.
    """
    for name in QUERY_DISPLAY_NAMES:
        if symbol_table is None or Symbol(name) not in symbol_table:
            return name
    return QUERY_DISPLAY_NAMES[-1]


def conditional_division_names(rule):
    """
    Name the probabilities of the rule dividing a conditional's parts.

    A conditional probability query ``P(A | B)`` is solved as the
    numerator ``P(A, B)`` (``cond_num``) and the denominator ``P(B)``
    (``cond_den``), divided by the rule
    ``q(…, p) :- q^cond_num(…, p1), q^cond_den(…, p2), p == p1 / p2``.
    For that rule, return the display names ``p``, ``p_num`` and
    ``p_den`` of its fresh variables ``p``, ``p1`` and ``p2``; for other
    rules, or should the rule use one of these names, an empty dict.
    """
    formulas = getattr(rule.antecedent, "formulas", ())
    roles = {}
    for formula in formulas:
        functor = getattr(formula, "functor", None)
        if isinstance(functor, AdornedSymbol) and functor.adornment in (
            "cond_num", "cond_den"
        ):
            for argument in formula.args:
                roles[argument] = functor.adornment
    variables = extract_logic_free_variables(
        rule.antecedent
    ) | extract_logic_free_variables(rule.consequent)
    used = {symbol.name for symbol in variables}
    for formula in formulas:
        names = _division_names(formula, roles)
        if names and not set(names.values()) & used:
            return names
    return {}


def _division_names(formula, roles):
    """Match ``p == p1 / p2``, ``p1`` (``p2``) of the numerator (denominator)."""
    if not (
        isinstance(formula, FunctionApplication)
        and formula.functor == Constant(operator.eq)
        and isinstance(formula.args[1], FunctionApplication)
        and formula.args[1].functor == Constant(operator.truediv)
    ):
        return {}
    result = formula.args[0]
    numerator, denominator = formula.args[1].args
    if (
        roles.get(numerator) != "cond_num"
        or roles.get(denominator) != "cond_den"
        or not all(
            isinstance(symbol, Symbol) and _FRESH_NAME.match(symbol.name)
            for symbol in (result, numerator, denominator)
        )
    ):
        return {}
    return {
        result.name: "p", numerator.name: "p_num", denominator.name: "p_den"
    }


class RenameSymbolsForDisplay(ExpressionWalker):
    """
    Rename predicate symbols, including adorned ones, for display.

    Parameters
    ----------
    renames : dict
        mapping from symbols to the symbols to display instead.

    """

    def __init__(self, renames):
        """Store the renames to apply."""
        self.renames = renames

    @add_match(AdornedSymbol)
    def adorned_symbol(self, symbol):
        """Rename the symbol an adorned symbol adorns."""
        base = symbol.expression
        if base not in self.renames:
            return symbol
        return AdornedSymbol(
            self.renames[base], symbol.adornment, symbol.number
        )

    @add_match(Symbol)
    def symbol(self, symbol):
        """Rename a symbol."""
        return self.renames.get(symbol, symbol)


class PlanDisplay:
    """
    Print the rules of a program and their relational algebra plans.

    Parameters
    ----------
    options : ShowRAOptions, optional
        how the plans are displayed, the default options when None.
    query_symbol : Symbol, optional
        predicate symbol generated for the query, displayed as ``ans``
        (or ``query`` if ``symbol_table`` has an ``ans`` predicate).
    symbol_table : Mapping, optional
        symbol table of the program.

    """

    def __init__(self, options=None, query_symbol=None, symbol_table=None):
        """Initialise the display; see the class docstring."""
        self.options = options or ShowRAOptions()
        self.query_name = query_display_name(symbol_table)
        self.renames = {}
        if query_symbol is not None:
            self.renames[query_symbol] = Symbol(self.query_name)

    def display_expression(self, expression):
        """Return ``expression`` with its symbols renamed for display."""
        if not self.renames:
            return expression
        return RenameSymbolsForDisplay(self.renames).walk(expression)

    def symbol_name(self, symbol):
        """Return the name ``symbol`` is displayed with."""
        symbol = self.display_expression(symbol)
        if isinstance(symbol, AdornedSymbol):
            return str(symbol)
        return symbol.name

    def rule_text(self, rule, fresh_map=None):
        """
        Return the Datalog text of ``rule``.

        The display names of its fresh variables are added to
        ``fresh_map``.
        """
        return DatalogPrettyPrinter(fresh_map).walk(
            self.display_expression(rule)
        )

    def name_map(self, conjunction, symbol_table):
        """
        Return the names the leaves of the plan of ``conjunction`` take.

        The leaves are named after the predicates of ``conjunction`` and
        the relations of ``symbol_table``.
        """
        name_map = build_name_map_from_conjunction(conjunction, symbol_table)
        for symbol in list(name_map):
            if isinstance(symbol, Symbol):
                name_map[symbol] = self.symbol_name(symbol)
        return name_map

    def print_rule(
        self, rule, conjunction, symbol_table, ra_code, leaf_sizes=None,
        column_roles=None, leaf_arities=None, notes=(), delta_symbols=(),
    ):
        """
        Print the ``--show-ra`` block of a rule.

        The block is the rule header (skipped when ``rule`` is None), the
        lines of ``notes``, then the pretty-printed RA plan ``ra_code``,
        whose tables are named after the predicates of ``conjunction`` and
        the relations of ``symbol_table``. ``leaf_sizes`` maps the
        predicate symbols of the plan whose size is known to their size.
        Columns named after a variable of the rule are displayed as the
        variable is in the rule header, and those in ``column_roles``
        with the label it maps them to. ``leaf_arities`` maps predicate
        symbols of the plan to the number of columns of their relation.
        Leaves of ``delta_symbols`` are bound to the tuples derived in the
        current iteration and printed as ``Δp``.
        """
        fresh_map = {}
        if rule is not None:
            fresh_map.update(conditional_division_names(rule))
            print(f"── rule {self.rule_text(rule, fresh_map)} ──")
        for note in notes:
            print(note)
        self.print_plan(
            conjunction, symbol_table, ra_code, leaf_sizes=leaf_sizes,
            column_roles=column_roles, leaf_arities=leaf_arities,
            delta_symbols=delta_symbols, fresh_map=fresh_map,
        )

    def print_plan(
        self, conjunction, symbol_table, ra_code, leaf_sizes=None,
        column_roles=None, leaf_arities=None, delta_symbols=(),
        fresh_map=None,
    ):
        """
        Print the RA plan ``ra_code`` (see :meth:`print_rule`).

        ``fresh_map`` maps the fresh variables of the rule the plan
        evaluates to their display name.
        """
        name_map = self.name_map(conjunction, symbol_table)
        for symbol in delta_symbols:
            name_map[symbol] = "Δ" + self.symbol_name(symbol)
        print(pretty_repr(
            ra_code, name_map=name_map, leaf_sizes=leaf_sizes,
            fresh_map=fresh_map, column_roles=column_roles,
            collapse=self.options.collapse, leaf_arities=leaf_arities,
        ))


@lru_cache(maxsize=None)
def show_ra_chase_class(chase_class):
    """Return ``chase_class`` extended with :class:`ShowRAChaseMixin`."""
    return type(
        f"ShowRA{chase_class.__name__}",
        (ShowRAChaseMixin, chase_class),
        {},
    )


def print_deterministic_ra_plan(
    chase_class, program, rules, options=None, query_symbol=None
):
    """
    Print the RA plans of the deterministic stratum ``rules``.

    The stratum is run with ``chase_class`` extended with
    :class:`ShowRAChaseMixin`, displaying the plans with the
    :class:`ShowRAOptions` ``options`` (the default ones when None), and
    the resulting chase solution is returned. ``query_symbol`` is the
    predicate generated for the query, displayed as ``ans``.
    """
    print("── deterministic stratum ──")
    display = PlanDisplay(options, query_symbol, program.symbol_table)
    chase = show_ra_chase(chase_class, program, rules, display)
    return chase.build_chase_solution()


def show_ra_chase(chase_class, program, rules, display=None):
    """
    Build a show-ra chase of ``rules`` over ``program``.

    The chase is an instance of ``chase_class`` extended with
    :class:`ShowRAChaseMixin`, which prints the plans with the
    :class:`PlanDisplay` ``display`` (a default one when None).
    """
    chase = show_ra_chase_class(chase_class)(program, rules=rules)
    chase.show_ra_display = display or PlanDisplay()
    return chase


def _leaf_sizes(predicates, symbol_table):
    """Return the sizes of the relations of the ``predicates``' symbols."""
    return {
        atom.functor: len(symbol_table[atom.functor].value)
        for atom in extract_logic_atoms(Conjunction(predicates))
        if isinstance(atom.functor, Symbol) and atom.functor in symbol_table
    }


def _leaf_arities(predicates, symbol_table):
    """Return the arities of the relations of the ``predicates``' symbols."""
    arities = {}
    for predicate in extract_logic_atoms(Conjunction(predicates)):
        functor = predicate.functor
        if isinstance(functor, Symbol) and functor in symbol_table:
            arities[functor] = symbol_table[functor].value.arity
    return arities


@dataclass
class RulePlan:
    """
    A plan a rule was evaluated with, and when.

    Parameters
    ----------
    conjunction : Conjunction
        body of the rule the plan evaluates.
    ra_code : Expression
        relational algebra plan.
    leaf_sizes : dict
        sizes of the relations of the plan's leaves, when fixed.
    leaf_arities : dict
        arities of the relations of the plan's leaves.
    deltas : frozenset
        predicate symbols bound to the tuples derived in the current
        iteration only (semi-naive evaluation).
    iterations : list
        iterations of the chase the plan was evaluated in.

    """

    conjunction: Conjunction
    ra_code: Expression
    leaf_sizes: dict
    leaf_arities: dict
    deltas: frozenset
    iterations: list


def aggregation_plan(rule, ra_code):
    """
    Return the plan of the aggregation rule ``rule`` over its body's plan.

    The chase evaluates the body with ``ra_code`` and groups the result
    by the variables of the consequent, applying its aggregations: this
    is shown as a ``γ`` node whose aggregate columns are named after the
    aggregations, e.g. ``γ[by=(l), count(x)]``.
    """
    printer = DatalogPrettyPrinter()
    groupby = []
    aggregates = []
    for argument in rule.consequent.args:
        if isinstance(argument, AggregationApplication):
            aggregates.append(FunctionApplicationListMember(
                argument.functor(*(
                    str2columnstr_constant(a.name)
                    if isinstance(a, Symbol) else a
                    for a in argument.args
                )),
                str2columnstr_constant(printer.walk(argument)),
            ))
        elif isinstance(argument, Symbol):
            groupby.append(str2columnstr_constant(argument.name))
    return GroupByAggregation(ra_code, tuple(groupby), tuple(aggregates))


def iterations_label(iterations):
    """Return ``iteration 1`` / ``iterations 2–4, 6`` for the iterations."""
    ranges = []
    for iteration in iterations:
        if ranges and iteration == ranges[-1][1] + 1:
            ranges[-1][1] = iteration
        else:
            ranges.append([iteration, iteration])
    text = ", ".join(
        str(first) if first == last else f"{first}–{last}"
        for first, last in ranges
    )
    plural = "s" if len(iterations) > 1 else ""
    return f"iteration{plural} {text}"


class ShowRAChaseMixin:
    """
    Chase mixin printing the named RA expression of each rule.

    The named RA plan each rule is evaluated with is recorded and, once
    the stratum is evaluated, printed: each rule once, with its plan, or
    with each of its plans and the iterations they were used in when the
    semi-naive evaluation binds predicates to their delta (``Δp``) in
    some iterations only. Iterative strata end with the number of
    iterations needed to reach the fixpoint. Errors raised while
    evaluating a rule (e.g. a predicate used with the wrong arity) reach
    the caller, as they do without show-ra. The plans are printed with
    the :class:`PlanDisplay` ``show_ra_display``.
    """

    show_ra_display = PlanDisplay()

    def __init__(self, *args, **kwargs):
        """Initialise the chase with no current rule."""
        super().__init__(*args, **kwargs)
        self._show_ra_current_rule = None
        self._show_ra_evaluations = {}
        self._show_ra_plans = None

    def execute_chase(self, rules, instance_update, instance):
        """Run the chase of a stratum, then print its rules' plans."""
        self._show_ra_plans = {}
        self._show_ra_evaluations = {}
        try:
            return super().execute_chase(rules, instance_update, instance)
        finally:
            self._print_show_ra_plans()

    def chase_step(self, instance, rule, restriction_instance=None):
        """Record ``rule`` as the current rule, then run the step."""
        self._show_ra_current_rule = rule
        self._show_ra_evaluations[rule] = (
            self._show_ra_evaluations.get(rule, 0) + 1
        )
        return super().chase_step(instance, rule, restriction_instance)

    def obtain_substitutions(
        self, rule_predicates_iterator, instance, restriction_instance
    ):
        """Record the RA plan of the current rule, then evaluate it."""
        predicates = tuple(rule_predicates_iterator)
        if not predicates:
            return []
        symbol_table = self.ra_symbol_table(
            predicates, instance, restriction_instance
        )
        self._record_show_ra_plan(
            predicates, symbol_table, restriction_instance
        )
        return super().obtain_substitutions(
            iter(predicates), instance, restriction_instance
        )

    def print_rule_plan(self, rule, symbol_table):
        """
        Print the plan ``rule`` would be evaluated with, without running it.

        The plan is the one the chase builds for ``rule``; the sizes of
        its leaves are those of the relations of ``symbol_table``.
        """
        rewritten = self.rewrite_antecedent_equalities(
            self.rewrite_constants_in_consequent(rule)
        )
        predicates = getattr(
            rewritten.antecedent, "formulas", (rewritten.antecedent,)
        )
        self._show_ra_current_rule = rule
        self._show_ra_plans = None
        self._record_show_ra_plan(predicates, symbol_table, {})

    def _is_iterative(self):
        """Return whether the chase iterates up to a fixpoint."""
        return isinstance(self, (ChaseNaive, ChaseSemiNaive))

    def _is_recursive(self):
        """Return whether the chase iterates over recursive rules."""
        derived = {rule.consequent.functor for rule in self.rules}
        return self._is_iterative() and any(
            atom.functor in derived
            for rule in self.rules
            for atom in extract_logic_atoms(rule.antecedent)
        )

    def _record_show_ra_plan(
        self, predicates, symbol_table, restriction_instance
    ):
        """Record the plan of the current rule evaluated on ``predicates``."""
        rule = self._show_ra_current_rule
        deltas = frozenset()
        if self._is_iterative() and restriction_instance:
            deltas = frozenset(
                predicate.functor for predicate in predicates
                if isinstance(predicate, FunctionApplication)
                and predicate.functor in restriction_instance
            )
        iteration = self._show_ra_evaluations.get(rule, 1)
        variants = self._show_ra_plans_of(rule)
        for plan in variants:
            if plan.deltas == deltas:
                plan.iterations.append(iteration)
                return
        conjunction = Conjunction(predicates)
        ra_code = self.translate_conjunction_to_named_ra(conjunction)
        if rule is not None and is_aggregation_rule(rule):
            ra_code = aggregation_plan(rule, ra_code)
        variants.append(RulePlan(
            conjunction,
            ra_code,
            self._show_ra_leaf_sizes(predicates, symbol_table),
            _leaf_arities(predicates, symbol_table),
            deltas,
            [iteration],
        ))
        if self._show_ra_plans is None:
            # Evaluated outside execute_chase: print right away.
            self._print_rule_plans(rule, variants)
            variants.clear()

    def _show_ra_plans_of(self, rule):
        """Return the list of plans recorded for ``rule``."""
        if self._show_ra_plans is None:
            return []
        return self._show_ra_plans.setdefault(rule, [])

    def _print_show_ra_plans(self):
        """Print the recorded plans of the stratum's rules."""
        plans, self._show_ra_plans = self._show_ra_plans, None
        if not plans:
            return
        for rule, variants in plans.items():
            self._print_rule_plans(rule, variants)
        if self._is_recursive():
            iterations = max(self._show_ra_evaluations.values(), default=0)
            plural = "s" if iterations > 1 else ""
            print(f"(fixpoint reached after {iterations} iteration{plural})")
        deltas = set().union(*(
            plan.deltas for variants in plans.values() for plan in variants
        ))
        for symbol in sorted(deltas, key=lambda symbol: symbol.name):
            name = self.show_ra_display.symbol_name(symbol)
            print(
                f"(Δ{name}: only the {name} tuples derived in the current "
                "iteration)"
            )

    def _print_rule_plans(self, rule, variants):
        """Print ``rule`` with its plans, labelled when there are many."""
        for position, plan in enumerate(variants):
            notes = ()
            if len(variants) > 1:
                notes = (f"{iterations_label(plan.iterations)}:",)
            self.show_ra_display.print_rule(
                rule if position == 0 else None,
                plan.conjunction,
                getattr(self, "datalog_program", None),
                plan.ra_code,
                plan.leaf_sizes,
                leaf_arities=plan.leaf_arities,
                notes=notes,
                delta_symbols=plan.deltas,
            )

    def _show_ra_leaf_sizes(self, predicates, symbol_table):
        """
        Return the sizes of the relations of ``predicates`` known for sure.

        The relations are those of ``symbol_table``, the one the plan is
        evaluated on. In iterative (recursive) strata, the relations
        derived by the stratum, which grow at each iteration, are left
        out.
        """
        varying = set()
        if self._is_iterative():
            varying = {rule.consequent.functor for rule in self.rules}
        sizes = {}
        for predicate in extract_logic_atoms(Conjunction(predicates)):
            functor = predicate.functor
            if (
                isinstance(functor, Symbol)
                and functor in symbol_table
                and functor not in varying
            ):
                sizes[functor] = len(symbol_table[functor].value)
        return sizes

    def pick_chase_instance_for_stratum(self, stratum, instance_update):
        """Wrap the inner per-stratum chase so its rules print RA too."""
        chase_instance = super().pick_chase_instance_for_stratum(
            stratum, instance_update
        )
        if chase_instance is None:
            return None
        wrapped = show_ra_chase(
            chase_instance.__class__,
            chase_instance.datalog_program,
            Union(tuple(chase_instance.rules)),
            self.show_ra_display,
        )
        wrapped.check_constraints(instance_update)
        return wrapped


def lineage_leaf_sizes_and_arities(plan, cpl):
    """
    Return the sizes and arities of the relations of a lineage plan.

    The leaves of ``plan`` are predicate symbols of the CP-Logic program
    ``cpl``; the arity of a probabilistic table leaves out its
    probability column, which the plan does not name.
    """
    probabilistic = set(cpl.probabilistic_facts()) | set(
        cpl.probabilistic_choices()
    )
    sizes, arities = {}, {}
    for node in plan_nodes(plan):
        if isinstance(node, Symbol) and node in cpl.symbol_table:
            relation = cpl.symbol_table[node].value
            sizes[node] = len(relation)
            arities[node] = relation.arity - (node in probabilistic)
    return sizes, arities


def probabilistic_table_names(cpl):
    """
    Map the probabilistic tables of a CP-Logic program to their predicate.

    The keys are the ``id`` of the constants holding the tables of the
    probabilistic facts and choices of ``cpl``, whose first column is
    the probability of each tuple.
    """
    return {
        id(table): symbol.name
        for tables in (cpl.probabilistic_facts(), cpl.probabilistic_choices())
        for symbol, table in tables.items()
    }


def probability_column_roles(plan, provenance_column, tables, rule):
    """
    Return the labels of the probability columns of a probabilistic plan.

    The provenance column of the result, ``provenance_column``, is
    labelled ``p``. The probability column of each table of ``tables``
    (see :func:`probabilistic_table_names`) named by ``plan`` is labelled
    ``p(<predicate>)``, numbered when a table is named more than once.
    Should the rule or the plan use ``p`` as a name, ``prob`` is used.
    """
    rule_variables = extract_logic_free_variables(
        rule.antecedent
    ) | extract_logic_free_variables(rule.consequent)
    names = plan_column_names(plan) | {
        symbol.name for symbol in rule_variables
    }
    label = next(
        candidate for candidate in ("p", "prob", "p_", "prob_")
        if candidate not in names
    )
    roles = {provenance_column: label}
    per_table = {}
    for node in plan_nodes(plan):
        if (
            isinstance(node, NameColumns)
            and isinstance(node.relation, Constant)
            and id(node.relation) in tables
        ):
            column = node.column_names[0].value
            per_table.setdefault(tables[id(node.relation)], []).append(column)
    for table, columns in per_table.items():
        columns = list(dict.fromkeys(columns))
        for number, column in enumerate(columns, start=1):
            suffix = subscript(number) if len(columns) > 1 else ""
            roles.setdefault(column, f"p({table}){suffix}")
    return roles


def plan_nodes(plan):
    """Yield the relational algebra operations and leaves of ``plan``."""
    yield plan
    if not isinstance(plan, RelationalAlgebraOperation):
        return
    for child in plan_children(plan):
        yield from plan_nodes(child)


def plan_children(node):
    """Return the operands of a relational algebra operation."""
    children = []
    for attribute in ("relation", "relation_left", "relation_right"):
        child = getattr(node, attribute, None)
        if isinstance(child, Expression):
            children.append(child)
    children.extend(getattr(node, "relations", ()))
    return tuple(children)


def plan_column_names(plan):
    """Return the names of the columns named by a plan's operators."""
    names = set()
    for node in plan_nodes(plan):
        if isinstance(node, RelationalAlgebraOperation):
            for argument in _flatten(node.unapply()):
                if isinstance(argument, Constant) and isinstance(
                    argument.value, ColumnStr
                ):
                    names.add(str(argument.value))
    return names


def _flatten(arguments):
    """Yield the arguments, and the items of tuple arguments, recursively."""
    for argument in arguments:
        if isinstance(argument, tuple):
            yield from _flatten(argument)
        elif isinstance(argument, FunctionApplicationListMember):
            yield from _flatten(argument.unapply())
        elif isinstance(argument, FunctionApplication):
            yield from _flatten(argument.args)
        else:
            yield argument


SOLVER_DESCRIPTIONS = {
    "small_dichotomy_theorem_based_solver":
        "small dichotomy theorem (safe plan)",
    "dalvi_suciu_lift": "Dalvi–Suciu lifted inference",
    "weighted_model_counting":
        "weighted model counting (knowledge compilation)",
}


def solver_description(solver):
    """Return a description of a probabilistic solver function."""
    module = getattr(solver, "__module__", "") or ""
    description = SOLVER_DESCRIPTIONS.get(module.rsplit(".", 1)[-1])
    if description is None:
        description = getattr(solver, "__qualname__", repr(solver))
    return description


def is_wmc_solver(solver):
    """Return whether ``solver`` is a weighted model counting solver."""
    module = getattr(solver, "__module__", "") or ""
    return module.rsplit(".", 1)[-1] == "weighted_model_counting"


@dataclass(frozen=True)
class ProbabilisticPlan:
    """
    The plan of a probabilistic query.

    Parameters
    ----------
    relation : Expression
        relational algebra plan.
    provenance_column : str or None
        column of ``relation`` holding the probability of each tuple.
    lineage : bool
        whether ``relation`` is a lineage plan, whose provenance is
        compiled to compute the probabilities, rather than a plan
        computing them.

    """

    relation: Expression
    provenance_column: object
    lineage: bool


class ShowRAStratumSolver(StratumSolver):
    """
    Print the RA plans of each stratum instead of evaluating it.

    The deterministic stratum is run with a show-ra chase, so that the
    probabilistic plans can be built over its solution. The plans of the
    probabilistic queries are not run, so those of the post-probabilistic
    stratum, which uses their results, are printed without being run.

    Parameters
    ----------
    engine : NeurolangPDL
        engine whose program is displayed.
    options : ShowRAOptions, optional
        how the plans are displayed, the default options when None.
    query_symbol : Symbol, optional
        predicate symbol generated for the query, displayed as ``ans``.

    """

    def __init__(self, engine, options=None, query_symbol=None):
        """Store the engine and how its plans are displayed."""
        super().__init__(engine)
        self.display = PlanDisplay(
            options, query_symbol, engine.program_ir.symbol_table
        )

    def deterministic(self, det_idb):
        """Print the RA plan of every deterministic rule."""
        print("── deterministic stratum ──")
        chase = show_ra_chase(
            self.engine.chase_class, self.engine.program_ir, det_idb,
            self.display,
        )
        return chase.build_chase_solution()

    def probabilistic(self, solution, prob_idb):
        """
        Print the RA plan of every probabilistic query.

        The plans are those of the solver the stratum is solved with: as
        in the evaluation, the first of the engine's solvers that can
        solve all of the stratum's queries. Probabilistic rules that are
        not queries are inlined in the queries using them.
        """
        print("── probabilistic stratum ──")
        engine = self.engine
        cpl, prob_idb = _build_probabilistic_program(
            solution,
            engine.program_ir.probabilistic_facts(),
            engine.program_ir.probabilistic_choices(),
            prob_idb,
            engine.check_qbased_pfact_tuple_unicity,
        )
        dedup = RemoveDuplicatedConjunctsDisjuncts()
        prob_idb = Union(tuple(dedup.walk(r) for r in prob_idb.formulas))
        queries = tuple(
            rule for rule in prob_idb.formulas
            if is_within_language_prob_query(rule)
        )
        solver, plans = self.stratum_plans(queries, cpl)
        for rule in prob_idb.formulas:
            if rule not in plans:
                print(f"── rule {self.display.rule_text(rule)} ──")
                print(
                    "(probabilistic rule: inlined into the queries using "
                    "it, it has no plan of its own)"
                )
        for rule in queries:
            self.print_probabilistic_plan(rule, plans[rule], solver, cpl)
        return solution

    def print_probabilistic_plan(self, rule, plan, solver, cpl):
        """Print the plan ``plan`` of the query ``rule`` solved by ``solver``."""
        notes = [f"[solver: {solver_description(solver)}]"]
        if plan.lineage:
            notes.append(
                "(lineage plan: its provenance is compiled into a decision "
                "diagram to compute the probabilities)"
            )
            column_roles = {}
            leaf_sizes, leaf_arities = lineage_leaf_sizes_and_arities(
                plan.relation, cpl
            )
        else:
            column_roles = probability_column_roles(
                plan.relation, plan.provenance_column,
                probabilistic_table_names(cpl), rule,
            )
            leaf_sizes, leaf_arities = {}, {}
        self.display.print_rule(
            rule,
            rule.antecedent,
            cpl.symbol_table,
            plan.relation,
            column_roles=column_roles,
            leaf_sizes=leaf_sizes,
            leaf_arities=leaf_arities,
            notes=notes,
        )

    def stratum_plans(self, queries, cpl):
        """
        Return the solver of the probabilistic ``queries`` and their plans.

        As in :meth:`NeurolangPDL._solve_probabilistic_stratum`, the
        solver is the first of the engine's solvers that solves every
        query; the plans map each query to its :class:`ProbabilisticPlan`.
        """
        if not queries:
            return None, {}
        solvers = self.engine.probabilistic_solvers
        for index, succ_solver in enumerate(solvers):
            try:
                return succ_solver, {
                    query: self.query_plan(query, cpl, succ_solver)
                    for query in queries
                }
            except UnsupportedSolverError:
                if index == len(solvers) - 1:
                    raise

    def print_query(self, head_symbols, atom, solution):
        """
        Print the restriction of a query predicate's relation to the query.

        The query ``ans(head_symbols) :- atom`` selects and projects the
        relation ``solution`` holds for the predicate of ``atom``. Nothing
        is printed when that predicate is the one generated for the query,
        already displayed as ``ans``.
        """
        functor = atom.functor
        while isinstance(functor, AdornedSymbol):
            functor = functor.expression
        if is_generated_symbol(functor):
            return
        rule = Implication(
            Symbol(self.display.query_name)(*head_symbols), atom
        )
        conjunction = Conjunction((atom,))
        ra_code = TranslateToNamedRA().walk(conjunction)
        ra_code = Projection(ra_code, tuple(
            str2columnstr_constant(symbol.name) for symbol in head_symbols
            if symbol in atom.args
        ))
        ra_code = RelationalAlgebraOptimiser().walk(ra_code)
        fresh_map = {}
        print(f"── query {self.display.rule_text(rule, fresh_map)} ──")
        self.display.print_plan(
            conjunction, solution, ra_code,
            leaf_sizes=_leaf_sizes((atom,), solution),
            leaf_arities=_leaf_arities((atom,), solution),
            fresh_map=fresh_map,
        )

    def postprobabilistic(self, solution, postprob_idb):
        """
        Print the RA plan of every post-probabilistic rule.

        The relations of the probabilistic queries are not computed, so
        the rules cannot be run: their plans, those the chase would run
        them with, are printed stratum by stratum.
        """
        print("── post-probabilistic stratum ──")
        program = self.engine._build_postprobabilistic_solver(
            solution, postprob_idb
        )
        chase = show_ra_chase(
            self.engine.chase_class, program, postprob_idb, self.display
        )
        strata, _ = stratify(postprob_idb, program)
        for stratum in strata:
            for rule in stratum:
                chase.print_rule_plan(rule, solution)
        return solution

    def rule_provenance_set(self, rule, cpl):
        """
        Build the provenance set of a probabilistic rule without solving it.

        The relational algebra solver is not run, so the returned set holds
        the unevaluated RA plan. The rule is solved by the first of the
        engine's solvers that can.
        """
        solvers = self.engine.probabilistic_solvers
        for succ_solver in solvers:
            try:
                return self._unevaluated_provenance_set(
                    rule, cpl, succ_solver
                )
            except UnsupportedSolverError:
                if succ_solver == solvers[-1]:
                    raise

    def query_plan(self, rule, cpl, succ_solver):
        """
        Return the :class:`ProbabilisticPlan` of ``rule`` by ``succ_solver``.

        The plans of the weighted model counting solver are their lineage
        plans, which are not run: that solver evaluates queries entirely.
        """
        if is_wmc_solver(succ_solver) and not isinstance(
            rule.antecedent, Condition
        ):
            query = within_language_succ_query_to_intensional_rule(rule)
            _, plan = wmc_prepare_and_translate_query(query, cpl)
            if isinstance(plan, ProvenanceAlgebraSet):
                return ProbabilisticPlan(
                    plan.relation, plan.provenance_column.value, False
                )
            return ProbabilisticPlan(plan, None, True)
        provenance_set = self._unevaluated_provenance_set(
            rule, cpl, succ_solver
        )
        return ProbabilisticPlan(
            provenance_set.relation,
            provenance_set.provenance_column.value,
            False,
        )

    def _unevaluated_provenance_set(self, rule, cpl, succ_solver):
        """Build the provenance set of ``rule`` by ``succ_solver``."""
        query = rule
        solve = self._solve_unevaluated_succ_query
        if is_within_language_prob_query(rule):
            query = within_language_succ_query_to_intensional_rule(rule)
            if isinstance(rule.antecedent, Condition):
                # As in the solver (_solve_within_language_prob_query), a
                # conditional query goes through the MARG solver, which
                # splits it into joint and conditioning SUCC queries and
                # does not run the RA solver on them.
                solve = self._solve_unevaluated_marg_query
        return solve(query, cpl, succ_solver)

    @staticmethod
    def _solve_unevaluated_succ_query(query, cpl, succ_solver):
        """Build the provenance set of a SUCC query without evaluating it."""
        return succ_solver(query, cpl, run_relational_algebra_solver=False)

    @staticmethod
    def _solve_unevaluated_marg_query(rule, cpl, succ_solver):
        """Build the provenance set of a MARG query without evaluating it."""
        return lift_solve_marg_query(rule, cpl, succ_solver)
